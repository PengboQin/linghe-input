#!/usr/bin/env python3
"""Derive complete syllables from the pinned public single-character dictionary."""
import pathlib,re,json,hashlib
root=pathlib.Path(__file__).resolve().parents[1];source=root/'resources/rime/private_pinyin.dict.yaml';out=root/'resources/semantic'
syllables=set()
for line in source.read_text().splitlines():
 cols=line.split('\t')
 if len(cols)>=2 and len(cols[0])==1 and re.fullmatch('[a-z]{1,8}',cols[1]):syllables.add(cols[1])
assert 300<=len(syllables)<=600
payload=('\n'.join(sorted(syllables))+'\n').encode();(out/'pinyin-syllables.txt').write_bytes(payload)
# The filter must enumerate possible spellings independently of word prediction.
header='// Generated by scripts/build_pinyin_syllables.py from the pinned public dictionary.\n// LGPL-3.0; see resources/semantic/PINYIN.json and resources/rime/licenses.\n#pragma once\nnamespace private_input {\ninline constexpr const char *pinyin_syllables[] = {\n'
header+=''.join('    "'+s+'",\n' for s in sorted(syllables))+'};\n}\n'
(root/'core/include/private_pinyin_syllables.h').write_text(header)
info={'count':len(syllables),'sha256':hashlib.sha256(payload).hexdigest(),'sourceSHA256':hashlib.sha256(source.read_bytes()).hexdigest(),'license':'LGPL-3.0, derived from bundled pinned Rime dictionaries; original notices preserved','purpose':'Distinguish full syllables from initials such as b; no input history'}
(out/'PINYIN.json').write_text(json.dumps(info,indent=2)+'\n');print(info)
