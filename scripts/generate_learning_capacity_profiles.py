#!/usr/bin/env python3
"""Generate small cross-platform capacity contracts; --check never writes.

The JSON is authoritative. This follows the existing repo's direct deterministic
asset generation pattern, without a framework or network/import side effects.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = Path('shared/contracts/learning-capacity-profiles-v1.json')
OUTPUTS = {
    'swift':Path('shared/PrivateInputKit/Sources/PrivateInputKit/LearningCapacityProfiles.swift'),
    'java':Path('android/app/src/main/java/live/linghe/privateinput/LearningCapacityProfiles.java'),
    'cpp':Path('core/include/learning_capacity_profiles.h'),
    'python':Path('server/cloud_learning/generated_capacity_profiles.py'),
}


def camel(value):
    head,*tail=value.split('_')
    return head+''.join(x.title() for x in tail)


def load(raw):
    value=json.loads(raw)
    if set(value)!={'schema','schema_version','sourceRoot','default_profile','policy','field_definitions','profiles'}:
        raise ValueError('capacity contract shape')
    if value['schema']!='private-input.learning-capacity-profiles' or type(value['schema_version']) is not int or value['schema_version']!=1 or value['sourceRoot']!='../..':
        raise ValueError('capacity contract schema')
    fields=value['field_definitions']
    if not isinstance(fields,dict) or not fields:
        raise ValueError('capacity fields')
    for name,field in fields.items():
        if not re.fullmatch('[a-z]+(?:_[a-z]+)*',name) or set(field)!={'unit','expands_in_v2','source_refs'}:
            raise ValueError('capacity field shape')
        if field['unit'] not in ('keys','positive_rows','bytes','records','components','producers','rows') or type(field['expands_in_v2']) is not bool:
            raise ValueError('capacity field unit')
        if not isinstance(field['source_refs'],list) or not field['source_refs'] or any(not isinstance(x,str) or not x for x in field['source_refs']):
            raise ValueError('capacity field provenance')
    identities=set()
    if not isinstance(value['profiles'],list) or not value['profiles']:
        raise ValueError('capacity profiles')
    for p in value['profiles']:
        if set(p)!={'profile_id','profile_version','limits'} or not isinstance(p['profile_id'],str) or not re.fullmatch('[a-z]+(?:-[a-z0-9]+)*',p['profile_id']):
            raise ValueError('capacity profile identity')
        if type(p['profile_version']) is not int or not 0<p['profile_version']<2**31:
            raise ValueError('capacity profile version')
        key=p['profile_id'],p['profile_version']
        if key in identities:raise ValueError('duplicate capacity profile')
        identities.add(key)
        if set(p['limits'])!=set(fields) or any(type(n) is not int or not 0<n<2**31 for n in p['limits'].values()):
            raise ValueError('capacity limits must match known fields and integer units')
    default=value['default_profile']
    if set(default)!={'profile_id','profile_version'} or type(default['profile_id']) is not str or type(default['profile_version']) is not int or (default['profile_id'],default['profile_version']) not in identities:
        raise ValueError('unknown default capacity profile')
    return value


def render(raw):
    value=load(raw);fields=list(value['field_definitions']);profiles=value['profiles']
    digest=hashlib.sha256(raw).hexdigest()
    notice='Generated by scripts/generate_learning_capacity_profiles.py; do not edit.\n'+str(CONTRACT)+' sha256='+digest
    names={p['profile_id']:camel(p['profile_id'].replace('-','_')) for p in profiles}
    args=lambda p:[json.dumps(p['profile_id']),str(p['profile_version'])]+[str(p['limits'][k])for k in fields]
    sw=['// '+notice.replace('\n','\n// '),'public struct LearningCapacityProfile: Equatable, Sendable {','    public let id: String','    public let version: Int']
    sw+=['    public let '+camel(k)+': Int'for k in fields]
    params=['id: String','version: Int']+[camel(k)+': Int'for k in fields]
    sw+=['    fileprivate init('+', '.join(params)+') {']+['        self.'+k+' = '+k for k in ['id','version']+[camel(k)for k in fields]]+['    }','}','public enum LearningCapacityProfileError: Error { case unknownProfile }','public enum LearningCapacityProfiles {']
    for p in profiles:
        labels=['id','version']+[camel(k)for k in fields]
        sw+=['    public static let '+names[p['profile_id']]+' = LearningCapacityProfile('+', '.join(k+': '+v for k,v in zip(labels,args(p)))+')']
    sw+=['    public static func require(id: String, version: Int) throws -> LearningCapacityProfile {']
    sw+=['        if id == '+names[p['profile_id']]+'.id && version == '+names[p['profile_id']]+'.version { return '+names[p['profile_id']]+' }'for p in profiles]
    sw+=['        throw LearningCapacityProfileError.unknownProfile','    }','}']
    ja=['// '+notice.replace('\n','\n// '),'package live.linghe.privateinput;','public final class LearningCapacityProfiles {','    private LearningCapacityProfiles() {}','    public static final class Profile {','        public final String id;','        public final int version;']
    ja+=['        public final int '+camel(k)+';'for k in fields]
    ja+=['        private Profile(String id, int version, '+', '.join('int '+camel(k)for k in fields)+') {']+['            this.'+k+' = '+k+';'for k in ['id','version']+[camel(k)for k in fields]]+['        }','    }']
    ja+=['    public static final Profile '+p['profile_id'].replace('-','_').upper()+' = new Profile('+', '.join(args(p))+');'for p in profiles]
    ja+=['    public static Profile require(String id, int version) {']
    ja+=['        if ('+p['profile_id'].replace('-','_').upper()+'.id.equals(id) && version == '+str(p['profile_version'])+') return '+p['profile_id'].replace('-','_').upper()+';'for p in profiles]
    ja+=['        throw new IllegalArgumentException("unknown learning capacity profile");','    }','}']
    cp=['// '+notice.replace('\n','\n// '),'#pragma once','#include <cstdint>','#include <string_view>','namespace private_input { namespace learning_capacity {','struct Profile {','    const std::string_view id;','    const uint32_t version;']
    cp+=['    const uint32_t '+k+';'for k in fields]
    cp+=['private:','    friend struct Definitions;','    constexpr Profile(std::string_view id, uint32_t version, '+', '.join('uint32_t '+k for k in fields)+') : '+', '.join(k+'('+k+')'for k in ['id','version']+fields)+' {}','};','struct Definitions {']
    cp+=['    inline static constexpr Profile '+p['profile_id'].replace('-','_')+'{'+', '.join(args(p))+'};'for p in profiles]
    cp+=['};']+['inline constexpr const Profile& '+p['profile_id'].replace('-','_')+' = Definitions::'+p['profile_id'].replace('-','_')+';'for p in profiles]
    cp+=['// Unknown id/version returns nullptr; consumers must reject that result.','inline constexpr const Profile* require_profile(std::string_view id, uint64_t version) noexcept {']
    cp+=['    if (id == '+p['profile_id'].replace('-','_')+'.id && version == '+str(p['profile_version'])+') return &'+p['profile_id'].replace('-','_')+';'for p in profiles]
    cp+=['    return nullptr;','}','}}']
    py=['# '+notice.replace('\n','\n# '),'from dataclasses import dataclass','','@dataclass(frozen=True)','class LearningCapacityProfile:','    id: str','    version: int']+['    '+k+': int'for k in fields]+['']
    py+=[p['profile_id'].replace('-','_').upper()+' = LearningCapacityProfile('+', '.join(args(p))+')'for p in profiles]
    py+=['','def require_profile(id, version):','    if type(id) is not str or type(version) is not int:','        raise ValueError("unknown learning capacity profile")']
    for p in profiles:
        name=p['profile_id'].replace('-','_').upper()
        py+=['    if id == '+name+'.id and version == '+name+'.version:','        return '+name]
    py+=['    raise ValueError("unknown learning capacity profile")']
    return {OUTPUTS[k]:('\n'.join(lines)+'\n').encode()for k,lines in [('swift',sw),('java',ja),('cpp',cp),('python',py)]}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--output-root',type=Path,default=ROOT)
    parser.add_argument('--contract',type=Path,default=ROOT/CONTRACT)
    args=parser.parse_args();outputs=render(args.contract.read_bytes());drift=[]
    for relative,raw in outputs.items():
        target=args.output_root/relative
        if args.check:
            if not target.is_file() or target.read_bytes()!=raw:drift.append(str(relative))
        else:
            target.parent.mkdir(parents=True,exist_ok=True)
            if not target.is_file() or target.read_bytes()!=raw:target.write_bytes(raw)
    if drift:raise SystemExit('Generated capacity profile drift: '+', '.join(drift))
    print(json.dumps({'generatedFiles':len(outputs),'checkOnly':args.check,'contractSha256':hashlib.sha256(args.contract.read_bytes()).hexdigest()}))


if __name__=='__main__':main()
