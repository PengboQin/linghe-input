#!/usr/bin/env python3
"""Pinned mainland automatic-candidate policy. Does not rewrite user text/data."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'resources/rime/charset/standard-8105.txt'
SOURCE = DATA.with_name('SOURCE.json')
POLICY = 'mainland-simplified-v1'


def load_tiers():
    raw = DATA.read_bytes()
    metadata = json.loads(SOURCE.read_text())
    if hashlib.sha256(raw).hexdigest() != metadata['sha256']:
        raise ValueError('Standard-character source hash changed')
    chars = raw.decode('utf-8').splitlines()
    if len(chars) != 8105 or len(set(chars)) != 8105 or any(len(c) != 1 for c in chars):
        raise ValueError('Invalid 8105-character standard table')
    return {c: 1 if i < 3500 else 2 if i < 6500 else 3 for i, c in enumerate(chars)}


TIERS = load_tiers()


def is_han(code):
    return (0x3400 <= code <= 0x4DBF or 0x4E00 <= code <= 0x9FFF or
            0xF900 <= code <= 0xFAFF or 0x20000 <= code <= 0x3FFFF or
            0x2E80 <= code <= 0x2FFF or 0x3100 <= code <= 0x312F or
            0x31A0 <= code <= 0x31BF or 0xE0100 <= code <= 0xE01EF)


def candidate_allowed(text):
    """Bound automatic Chinese output; retain Latin, numbers, punctuation/emoji."""
    return bool(text) and all(not (0xD800 <= ord(c) <= 0xDFFF) and
                              (not is_han(ord(c)) or c in TIERS)
                              for c in text)


def candidate_tier(text):
    return max((TIERS.get(c, 0) for c in text), default=0)


def generated_header():
    rows = sorted((ord(c), tier) for c, tier in TIERS.items())
    lines = ['// Generated by scripts/mainland_lexicon_policy.py; do not edit.',
             '// MIT source attribution: resources/rime/charset/MIT-LICENSE.txt',
             '// Standard table checksum is pinned in resources/rime/charset/SOURCE.json.',
             '#pragma once', '#include <cstdint>',
             'namespace private_input { namespace mainland {',
             'struct StandardCharacter { uint32_t code; unsigned char tier; };',
             'inline constexpr StandardCharacter standard_characters[] = {']
    for start in range(0, len(rows), 8):
        lines.append('  ' + ','.join('{0x%Xu,%d}' % p for p in rows[start:start+8]) + ',')
    lines += ['};', '}}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-header', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'core/include/private_standard_characters.h'
    content = generated_header()
    if args.write_header:
        path.write_text(content)
    elif not path.is_file() or path.read_text() != content:
        raise SystemExit('Generated character header differs from pinned data')
    print(json.dumps({'policy': POLICY, 'characters': len(TIERS), 'tiers': [3500,3000,1605], 'headerVerified': True}))
